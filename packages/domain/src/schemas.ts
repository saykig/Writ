/**
 * Loads vendored JSON Schemas copied from the authoritative `schemas/` tree.
 * Schemas are read from
 * `packages/domain/schemas/` relative to this module so resolution works the
 * same for consumers and for the test runner.
 */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import {
  EMBEDDED_COMPATIBILITY_SCHEMA_TEXT,
  EMBEDDED_CORPUS_COMPATIBILITY_CONTRACT_TEXT,
  EMBEDDED_SCHEMA_TEXT,
} from "./schemas.embedded.js";

/** The canonical set of schema kinds, ordered. */
